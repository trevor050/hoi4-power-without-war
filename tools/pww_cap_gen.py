#!/usr/bin/env python3
"""Generate the capacity lane's per-resource script (HoI4 has no $PARAM$ in
scripted effects, so every resource gets its own block).

Writes:
    mod/common/scripted_effects/pww_cap_res.txt
    mod/common/dynamic_modifiers/pww_cap_dynamic_modifiers.txt
    mod/localisation/english/pww_cap_l_english.yml

Hand-written (not generated): mod/common/scripted_effects/pww_cap_core.txt
(model, tunables, scheduler, economic system, debug) and
mod/common/on_actions/pww_cap_on_actions.txt.

Engine facts the formulas rest on (probes tests/probes/cap_probe and
export_probe, 2026-11-26):
  - resource_produced is NET of country_resource_cost and includes
    country_resource inflows (contract purchases, reserve draws, dumps).
  - resource_exported is the open-market pool on offer (export share x
    produced), not what was sold; the world buys a small part of it.
  - resource@ = produced - consumed - pool + imports, so a cost of X lowers
    the balance by (1 - export share) x X only.

Usage: python tools/pww_cap_gen.py
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MOD = REPO / "mod"

RES = ["oil", "aluminium", "rubber", "tungsten", "steel", "chromium", "coal"]
# Oil has no stockpile or cartel (vanilla stores spare oil as fuel).
STORED = set(RES) - {"oil"}

HEADER = "# GENERATED by tools/pww_cap_gen.py. Edit the generator, then rerun it.\n"


def block(lines: list[str], depth: int) -> str:
    return "".join("\t" * depth + ln + "\n" if ln else "\n" for ln in lines)


def tick(r: str) -> str:
    stored = r in STORED
    # Own flows that the engine books as production (in) or cost (out).
    own_in = [f"pww_lf_in_{r}"] + ([f"pww_stock_out_{r}", f"pww_cartel_dump_{r}"] if stored else [])
    own_out = [f"pww_lf_out_{r}"] + ([f"pww_stock_cost_{r}", f"pww_cartel_hold_{r}"] if stored else [])
    # Our own lanes' flows to take out of the balance (contracts stay: they
    # are real sales and purchases).
    lane_out = [f"pww_stock_cost_{r}", f"pww_cartel_hold_{r}"] if stored else []
    lane_in = [f"pww_stock_out_{r}", f"pww_cartel_dump_{r}"] if stored else []

    L = []
    L += ["# Extraction (own output): produced is net of costs and includes",
          "# inflows, so add the costs back and take the inflows out.",
          f"set_temp_variable = {{ pww_cpk_p = resource_produced@{r} }}",
          "set_temp_variable = { pww_cpk_own = pww_cpk_p }"]
    L += [f"subtract_from_temp_variable = {{ pww_cpk_own = {v} }}" for v in own_in]
    L += [f"add_to_temp_variable = {{ pww_cpk_own = {v} }}" for v in own_out]
    L += ["if = {",
          f"\tlimit = {{ NOT = {{ has_variable = pww_cap_{r} }} }}",
          f"\tset_variable = {{ pww_cap_{r} = 1 }}",
          f"\tset_variable = {{ pww_cap_trend_{r} = 0 }}",
          "}",
          f"set_temp_variable = {{ pww_cpk_cap = pww_cap_{r} }}",
          "set_temp_variable = { pww_cpk_tr = 0 }",
          "set_temp_variable = { pww_cpk_ok = 0 }",
          "if = {",
          "\tlimit = { check_variable = { pww_cpk_own > global.pww_cap_c_min_out } }"]
    I = []  # inside the producing branch
    I += ["# Export share in force: the pool on offer over production.",
          f"set_temp_variable = {{ pww_cpk_x = resource_exported@{r} }}",
          "set_temp_variable = { pww_cpk_e = 0 }",
          "if = {",
          "\tlimit = { check_variable = { pww_cpk_p > 0.5 } }",
          "\tset_temp_variable = { pww_cpk_e = pww_cpk_x }",
          "\tdivide_temp_variable = { pww_cpk_e = pww_cpk_p }",
          "\tclamp_temp_variable = { var = pww_cpk_e min = 0 max = 1 }",
          "}",
          "set_temp_variable = { pww_cpk_ne = 1 }",
          "subtract_from_temp_variable = { pww_cpk_ne = pww_cpk_e }",
          "# Natural balance: resource@ without our lanes' holding, storage costs,",
          "# reserve draws and dumps (each moves the balance by (1 - e) of itself).",
          f"set_temp_variable = {{ pww_cpk_b = resource@{r} }}",
          "set_temp_variable = { pww_cpk_lf = 0 }"]
    I += [f"add_to_temp_variable = {{ pww_cpk_lf = {v} }}" for v in lane_out]
    I += [f"subtract_from_temp_variable = {{ pww_cpk_lf = {v} }}" for v in lane_in]
    I += ["multiply_temp_variable = { pww_cpk_lf = pww_cpk_ne }",
          "set_temp_variable = { pww_cpk_bn = pww_cpk_b }",
          "add_to_temp_variable = { pww_cpk_bn = pww_cpk_lf }",
          "# Unsold = natural balance less what storage takes; spare = unsold",
          "# beyond the working margin (c_margin of extraction).",
          "set_temp_variable = { pww_cpk_stin = 0 }"]
    if stored:
        I += ["if = {",
              "\tlimit = { has_global_flag = pww_stock_loaded }",
              f"\tset_temp_variable = {{ pww_cpk_stin = pww_stock_in_{r} }}",
              "}"]
    I += ["set_temp_variable = { pww_cpk_u = pww_cpk_bn }",
          "subtract_from_temp_variable = { pww_cpk_u = pww_cpk_stin }",
          "set_temp_variable = { pww_cpk_m = pww_cpk_own }",
          "multiply_temp_variable = { pww_cpk_m = global.pww_cap_c_margin }",
          "set_temp_variable = { pww_cpk_s = pww_cpk_u }",
          "subtract_from_temp_variable = { pww_cpk_s = pww_cpk_m }",
          f"set_variable = {{ pww_cap_spare_{r} = pww_cpk_s }}",
          "",
          "# Own shortage: without vanilla imports and contract purchases the",
          "# country's own balance is negative (it imports, draws reserves or",
          "# goes without).",
          "set_temp_variable = { pww_cpk_bo = pww_cpk_bn }",
          f"subtract_from_temp_variable = {{ pww_cpk_bo = resource_imported@{r} }}",
          f"set_temp_variable = {{ pww_cpk_t = pww_lf_in_{r} }}",
          "multiply_temp_variable = { pww_cpk_t = pww_cpk_ne }",
          "subtract_from_temp_variable = { pww_cpk_bo = pww_cpk_t }",
          f"set_temp_variable = {{ pww_cpk_tol = resource_consumed@{r} }}",
          "multiply_temp_variable = { pww_cpk_tol = global.pww_cap_c_short_share }",
          "if = { limit = { check_variable = { pww_cpk_tol < global.pww_cap_c_short_min } } set_temp_variable = { pww_cpk_tol = global.pww_cap_c_short_min } }",
          "multiply_temp_variable = { pww_cpk_tol = -1 }",
          "set_temp_variable = { pww_cpk_short = 0 }",
          "if = {",
          "\tlimit = { check_variable = { pww_cpk_bo < pww_cpk_tol } }",
          "\tset_temp_variable = { pww_cpk_short = 1 }",
          "}",
          "",
          "# World market: the share of the world's open-market pool that buyers",
          "# take (global.pww_cap_rho_<res>). Nobody idles below c_rho_mult x",
          "# that share (vanilla buyers keep their imports); a tight world",
          "# market (share over c_pool_full) is demand.",
          f"set_temp_variable = {{ pww_cpk_rho = global.pww_cap_rho_{r} }}",
          "set_temp_variable = { pww_cpk_fl = pww_cpk_rho }",
          "multiply_temp_variable = { pww_cpk_fl = global.pww_cap_c_rho_mult }",
          "if = { limit = { check_variable = { pww_cpk_fl < global.pww_cap_c_floor } } set_temp_variable = { pww_cpk_fl = global.pww_cap_c_floor } }",
          "if = { limit = { check_variable = { pww_cpk_fl > 1 } } set_temp_variable = { pww_cpk_fl = 1 } }",
          "set_temp_variable = { pww_cpk_full = 0 }",
          "if = {",
          "\tlimit = { check_variable = { pww_cpk_rho > global.pww_cap_c_pool_full } }",
          "\tset_temp_variable = { pww_cpk_full = 1 }",
          "}",
          "",
          "# Other demand: contract buyers are taking the working stock, a buyer",
          f"# was turned away (country var pww_cap_turned_{r} = the day), test hook.",
          "set_temp_variable = { pww_cpk_dmd = 0 }",
          "set_temp_variable = { pww_cpk_t = pww_cpk_m }",
          "multiply_temp_variable = { pww_cpk_t = global.pww_cap_c_low_stock }",
          "if = {",
          "\tlimit = {",
          "\t\tcheck_variable = { pww_cpk_u < pww_cpk_t }",
          f"\t\tcheck_variable = {{ pww_lf_out_{r} > 0.5 }}",
          "\t}",
          "\tset_temp_variable = { pww_cpk_dmd = 1 }",
          "}",
          "if = {",
          f"\tlimit = {{ has_variable = pww_cap_turned_{r} }}",
          "\tset_temp_variable = { pww_cpk_t = global.num_days }",
          f"\tsubtract_from_temp_variable = {{ pww_cpk_t = pww_cap_turned_{r} }}",
          "\tif = {",
          "\t\tlimit = { check_variable = { pww_cpk_t < global.pww_cap_c_turned_days } }",
          "\t\tset_temp_variable = { pww_cpk_dmd = 1 }",
          "\t}",
          "}"]
    if not stored:
        I += ["# Oil: fuel tanks running low (war) are demand for oil.",
              "if = {",
              "\tlimit = { fuel_ratio < 0.5 }",
              "\tset_temp_variable = { pww_cpk_dmd = 1 }",
              "}"]
    I += ["if = {",
          f"\tlimit = {{ has_variable = pww_cap_test_demand_{r} }}",
          "\tset_temp_variable = { pww_cpk_dmd = 1 }",
          "}",
          "set_temp_variable = { pww_cpk_sold = 0 }",
          "if = {",
          "\tlimit = {",
          "\t\tNOT = { check_variable = { pww_cpk_s > 0 } }",
          "\t\tOR = {",
          "\t\t\tcheck_variable = { pww_cpk_full = 1 }",
          "\t\t\tcheck_variable = { pww_cpk_short = 1 }",
          "\t\t\tcheck_variable = { pww_cpk_dmd = 1 }",
          "\t\t}",
          "\t}",
          "\tset_temp_variable = { pww_cpk_sold = 1 }",
          "}",
          "",
          "# May this output idle? Spare persists, storage takes nothing more,",
          "# the factor stays above the world-market floor, and the economic",
          "# system allows it.",
          "# Deadband: idle only when spare exceeds c_idle_band of extraction, so",
          "# a seller at balance neither idles nor expands.",
          "set_temp_variable = { pww_cpk_t = pww_cpk_fl }",
          "add_to_temp_variable = { pww_cpk_t = 0.001 }",
          "set_temp_variable = { pww_cpk_bd = pww_cpk_own }",
          "multiply_temp_variable = { pww_cpk_bd = global.pww_cap_c_idle_band }",
          "if = {",
          "\tlimit = {",
          "\t\tcheck_variable = { pww_cpk_s > pww_cpk_bd }",
          "\t\tcheck_variable = { pww_cpk_cap > pww_cpk_t }",
          "\t\tNOT = { check_variable = { pww_cap_sys = 1 } }",
          "\t}",
          "\tset_temp_variable = { pww_cpk_ok = 1 }"]
    if stored:
        I += ["\t# Storage fills first: no idling while the reserve still takes output.",
              "\tif = {",
              "\t\tlimit = {",
              "\t\t\thas_global_flag = pww_stock_loaded",
              "\t\t\tcheck_variable = { pww_cpk_stin > 0.099 }",
              f"\t\t\tNOT = {{ pww_stock_full_{r} = yes }}",
              "\t\t}",
              "\t\tset_temp_variable = { pww_cpk_ok = 0 }",
              "\t}"]
    else:
        I += ["\t# Spare oil fills the fuel tanks: idle only once they are full.",
              "\tif = {",
              "\t\tlimit = { NOT = { fuel_ratio > 0.95 } }",
              "\t\tset_temp_variable = { pww_cpk_ok = 0 }",
              "\t}"]
    I += ["\t# Command economy: keeps output it uses for war production.",
          f"\tset_temp_variable = {{ pww_cpk_use = resource_consumed@{r} }}",
          "\tif = {",
          "\t\tlimit = {",
          "\t\t\tcheck_variable = { pww_cap_sys = 2 }",
          "\t\t\tOR = {",
          "\t\t\t\tcheck_variable = { pww_cpk_use > global.pww_cap_c_mil_use }",
          "\t\t\t\tcheck_variable = { pww_cpk_short = 1 }",
          "\t\t\t}",
          "\t\t}",
          "\t\tset_temp_variable = { pww_cpk_ok = 0 }",
          "\t}",
          "}",
          "",
          "if = {",
          "\tlimit = { check_variable = { pww_cpk_ok = 1 } }",
          "\tsubtract_from_temp_variable = { pww_cpk_cap = global.pww_cap_c_idle }",
          "\tif = { limit = { check_variable = { pww_cpk_cap < pww_cpk_fl } } set_temp_variable = { pww_cpk_cap = pww_cpk_fl } }",
          "\tset_temp_variable = { pww_cpk_tr = -1 }",
          "}",
          "else_if = {",
          "\t# Reopen idle output: sold out, or idled below the world-market floor.",
          "\tlimit = {",
          "\t\tcheck_variable = { pww_cpk_cap < 0.999 }",
          "\t\tOR = {",
          "\t\t\tcheck_variable = { pww_cpk_sold = 1 }",
          "\t\t\tcheck_variable = { pww_cpk_cap < pww_cpk_fl }",
          "\t\t}",
          "\t}",
          "\tadd_to_temp_variable = { pww_cpk_cap = global.pww_cap_c_reopen }",
          "\tif = { limit = { check_variable = { pww_cpk_cap > 1 } } set_temp_variable = { pww_cpk_cap = 1 } }",
          "\tset_temp_variable = { pww_cpk_tr = 1 }",
          "}",
          "else_if = {",
          "\t# Invest: a market economy for any buyer; planned and command",
          "\t# economies only where the country itself is short.",
          "\tlimit = {",
          "\t\tcheck_variable = { pww_cpk_sold = 1 }",
          "\t\tcheck_variable = { pww_cpk_cap > 0.998 }",
          "\t\tcheck_variable = { pww_cpk_cap < global.pww_cap_c_ceiling }",
          "\t\tOR = {",
          "\t\t\tcheck_variable = { pww_cap_sys = 0 }",
          "\t\t\tcheck_variable = { pww_cpk_short = 1 }",
          "\t\t}",
          "\t}",
          "\tset_temp_variable = { pww_cpk_t = global.pww_cap_c_invest_market }",
          "\tif = { limit = { check_variable = { pww_cap_sys = 1 } } set_temp_variable = { pww_cpk_t = global.pww_cap_c_invest_planned } }",
          "\tif = { limit = { check_variable = { pww_cap_sys = 2 } } set_temp_variable = { pww_cpk_t = global.pww_cap_c_invest_command } }",
          "\tadd_to_temp_variable = { pww_cpk_cap = pww_cpk_t }",
          "\tif = { limit = { check_variable = { pww_cpk_cap > global.pww_cap_c_ceiling } } set_temp_variable = { pww_cpk_cap = global.pww_cap_c_ceiling } }",
          "\tset_temp_variable = { pww_cpk_tr = 2 }",
          "}",
          f"set_variable = {{ pww_cap_{r} = pww_cpk_cap }}"]
    L2 = ["}",
          f"set_variable = {{ pww_cap_trend_{r} = pww_cpk_tr }}",
          "# Modifier value: the factor relative to vanilla output. The per-resource",
          "# factor adds to local_resources_factor (technology), so scale by it.",
          f"set_temp_variable = {{ pww_cpk_mv = pww_cap_{r} }}",
          "subtract_from_temp_variable = { pww_cpk_mv = 1 }",
          "multiply_temp_variable = { pww_cpk_mv = pww_cpk_lrf }",
          f"set_variable = {{ pww_cap_m_{r} = pww_cpk_mv }}",
          "if = {",
          "\tlimit = { has_global_flag = pww_cap_debug }",
          f'\tlog = "[GetDateText] PWW_CAP [This.GetTag] {r} sys=[?pww_cap_sys|0] cap=[?pww_cap_{r}|3] trend=[?pww_cap_trend_{r}|0] own=[?pww_cpk_own|1] bal=[?pww_cpk_b|1] unsold=[?pww_cpk_u|1] spare=[?pww_cpk_s|1] pool=[?pww_cpk_x|1] rho=[?pww_cpk_rho|3] fl=[?pww_cpk_fl|2] short=[?pww_cpk_short|0] dmd=[?pww_cpk_dmd|0] ok=[?pww_cpk_ok|0]"',
          "}"]
    return (f"### {r}\n\npww_cap_tick_{r} = {{\n" + block(L, 1) + block(I, 2) + block(L2, 1) + "}\n\n")


def world() -> str:
    L = ["# Any scope. Per resource, the share of the world's open-market pool that",
         "# buyers take: global.pww_cap_rho_<res> = world imports / world pool.",
         "pww_cap_world_refresh = {"]
    for r in RES:
        L += [f"\tset_temp_variable = {{ pww_cpk_wx = 0 }}",
              f"\tset_temp_variable = {{ pww_cpk_wi = 0 }}",
              "\tevery_country = {",
              "\t\tlimit = { exists = yes }",
              f"\t\tadd_to_temp_variable = {{ pww_cpk_wx = resource_exported@{r} }}",
              f"\t\tadd_to_temp_variable = {{ pww_cpk_wi = resource_imported@{r} }}",
              "\t}",
              "\tif = { limit = { check_variable = { pww_cpk_wx < 1 } } set_temp_variable = { pww_cpk_wx = 1 } }",
              "\tdivide_temp_variable = { pww_cpk_wi = pww_cpk_wx }",
              "\tclamp_temp_variable = { var = pww_cpk_wi min = 0 max = 2 }",
              f"\tset_variable = {{ global.pww_cap_rho_{r} = pww_cpk_wi }}"]
    L += ["\tset_variable = { global.pww_cap_world_day = global.num_days }",
          "\tif = {",
          "\t\tlimit = { has_global_flag = pww_cap_debug }",
          "\t\tlog = \"[GetDateText] PWW_CAP world rho " + " ".join(
              f"{r[:3]}=[?global.pww_cap_rho_{r}|3]" for r in RES) + "\"",
          "\t}",
          "}", ""]
    return "\n".join(L) + "\n"


def effects() -> str:
    out = [HEADER, """###############################################################################
# Power Without War: capacity, per-resource effects (model, tunables and the
# public interface: pww_cap_core.txt).
#
#   pww_cap_tick_<res>     (country) read the signals, move the factor one
#                          monthly step, write pww_cap_<res>, pww_cap_trend_<res>,
#                          pww_cap_spare_<res> and the modifier value
#                          pww_cap_m_<res>. Needs temp pww_cpk_lrf (1 +
#                          local_resources_factor when c_comp = 1, else 1).
#   pww_cap_world_refresh  (any) global.pww_cap_rho_<res>
###############################################################################

"""]
    for r in RES:
        out.append(tick(r))
    out.append(world())
    out.append("# All seven resources (called by pww_cap_core.txt).\n")
    out.append("pww_cap_tick_all = {\n" + "".join(f"\tpww_cap_tick_{r} = yes\n" for r in RES) + "}\n\n")
    out.append("# Country scope. Resets every factor to vanilla (pww_cap_reset).\n")
    out.append("pww_cap_reset_all = {\n" + "".join(
        f"\tset_variable = {{ pww_cap_{r} = 1 }}\n\tset_variable = {{ pww_cap_trend_{r} = 0 }}\n\tset_variable = {{ pww_cap_m_{r} = 0 }}\n"
        for r in RES) + "}\n")
    return "".join(out)


def modifiers() -> str:
    lines = [HEADER, """###############################################################################
# Power Without War: capacity dynamic modifier (one per producing country).
#   pww_cap_m_<res>  local_resources_<res>_factor: output relative to vanilla
#                    minus 1 (pww_cap_<res> 0.5..1.3), scaled by technology
# Written by pww_cap_tick_<res> (pww_cap_res.txt).
###############################################################################

pww_cap_output = {
	enable = { always = yes }
	icon = GFX_idea_export_focus

"""]
    for r in RES:
        lines.append(f"\tlocal_resources_{r}_factor = pww_cap_m_{r}\n")
    lines.append("}\n")
    return "".join(lines)


def loc() -> str:
    entries = [
        ("pww_cap_output", "Output Follows Demand"),
        ("pww_cap_output_desc",
         "Mines, wells and plantations run below capacity when their output finds no buyer, "
         "and reopen or expand when buyers return. Reopening idle capacity takes months."),
        ("pww_cap_sys_0", "Market economy"),
        ("pww_cap_sys_1", "Planned economy"),
        ("pww_cap_sys_2", "Command economy"),
        ("pww_cap_trend_n1", "Output idling"),
        ("pww_cap_trend_0", "Output steady"),
        ("pww_cap_trend_1", "Reopening idle output"),
        ("pww_cap_trend_2", "Expanding"),
    ]
    return "﻿l_english:\n" + "".join(f' {k}: "{v}"\n' for k, v in entries)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    print(f"wrote {path.relative_to(REPO)}")


def main() -> None:
    write(MOD / "common/scripted_effects/pww_cap_res.txt", effects())
    write(MOD / "common/dynamic_modifiers/pww_cap_dynamic_modifiers.txt", modifiers())
    write(MOD / "localisation/english/pww_cap_l_english.yml", loc())


if __name__ == "__main__":
    main()
