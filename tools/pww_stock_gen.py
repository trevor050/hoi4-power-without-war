#!/usr/bin/env python3
"""Generate the stockpiles lane's per-resource script (HoI4 has no $PARAM$ in
scripted effects, so every resource gets its own block).

Writes:
    mod/common/scripted_effects/pww_stock_res.txt
    mod/common/scripted_triggers/pww_stock_triggers.txt
    mod/common/dynamic_modifiers/pww_stock_dynamic_modifiers.txt
    mod/localisation/english/pww_stock_l_english.yml

Hand-written (not generated): pww_stock_core.txt (scheduler, constants,
capitulation, AI depots), pww_stock_on_actions.txt, pww_stock_decisions.txt,
pww_stock_categories.txt.

Usage: python tools/pww_stock_gen.py
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MOD = REPO / "mod"

# Oil is excluded: vanilla already turns spare oil into the fuel stockpile.
RES = ["aluminium", "rubber", "tungsten", "steel", "chromium", "coal"]
NAMES = {
    "aluminium": "Aluminium",
    "rubber": "Rubber",
    "tungsten": "Tungsten",
    "steel": "Steel",
    "chromium": "Chromium",
    "coal": "Coal",
}

HEADER = "# GENERATED by tools/pww_stock_gen.py. Edit the generator, then rerun it.\n"


def tmin(var: str, other: str) -> str:
    return f"\t\tif = {{ limit = {{ check_variable = {{ {var} > {other} }} }} set_temp_variable = {{ {var} = {other} }} }}\n"


def effects() -> str:
    out = [HEADER, """###############################################################################
# Power Without War: stockpiles, per-resource effects (see pww_stock_core.txt
# for the model, constants and the public interface).
#
#   pww_stock_tick_<res>    (country) accrue + decay since the last tick, read
#                           the stable balance, set this period's fill or draw
#                           rate. Needs temps pww_stk_el (days since the last
#                           tick) and pww_stk_e (export share, modifier
#                           min_export) from pww_stock_country_tick.
#   pww_stock_cap_<res>     (country) capacity, fill %, days of use covered.
#   pww_stock_value_<res>   (country) temp out pww_stock_unit_value: what one
#                           unit a day of <res> put in THIS country's reserve
#                           is worth, in civilian factories.
#   pww_stock_seize_<res>   (capitulated country, FROM = occupier) moves the
#                           seized share to FROM.
###############################################################################

"""]
    for r in RES:
        out.append(f"""### {r}

pww_stock_tick_{r} = {{
	# Accrue the rates in force since the last tick.
	set_temp_variable = {{ pww_stk_d = pww_stock_in_{r} }}
	subtract_from_temp_variable = {{ pww_stk_d = pww_stock_out_{r} }}
	multiply_temp_variable = {{ pww_stk_d = pww_stk_el }}
	add_to_variable = {{ pww_stock_{r} = pww_stk_d }}
	# Decay: global.pww_stock_c_decay of the stock per 30 days.
	set_temp_variable = {{ pww_stk_d = pww_stock_{r} }}
	multiply_temp_variable = {{ pww_stk_d = global.pww_stock_c_decay }}
	multiply_temp_variable = {{ pww_stk_d = pww_stk_el }}
	divide_temp_variable = {{ pww_stk_d = 30 }}
	subtract_from_variable = {{ pww_stock_{r} = pww_stk_d }}
	clamp_variable = {{ var = pww_stock_{r} min = 0 max = 1000000 }}

	# Stable balance B: what resource@ would read without our own flows.
	#   cost = the part of the intake applied as country_resource_cost (cartel
	#          withholding, or all of it when c_fill_cost = 1)
	#   leak = clamp(exported - (produced - out) x share, 0, out x share)
	#          (part of a draw re-exported under the trade law)
	#   B    = resource@ + cost - out + leak
	set_temp_variable = {{ pww_stk_p = resource_produced@{r} }}
	subtract_from_temp_variable = {{ pww_stk_p = pww_stock_out_{r} }}
	set_temp_variable = {{ pww_stk_lk = pww_stk_p }}
	multiply_temp_variable = {{ pww_stk_lk = pww_stk_e }}
	multiply_temp_variable = {{ pww_stk_lk = -1 }}
	add_to_temp_variable = {{ pww_stk_lk = resource_exported@{r} }}
	set_temp_variable = {{ pww_stk_m = pww_stock_out_{r} }}
	multiply_temp_variable = {{ pww_stk_m = pww_stk_e }}
	if = {{ limit = {{ check_variable = {{ pww_stk_lk > pww_stk_m }} }} set_temp_variable = {{ pww_stk_lk = pww_stk_m }} }}
	clamp_temp_variable = {{ var = pww_stk_lk min = 0 max = 1000000 }}
	set_temp_variable = {{ pww_stk_b = resource@{r} }}
	add_to_temp_variable = {{ pww_stk_b = pww_stock_cost_{r} }}
	subtract_from_temp_variable = {{ pww_stk_b = pww_stock_out_{r} }}
	add_to_temp_variable = {{ pww_stk_b = pww_stk_lk }}
	set_variable = {{ pww_stock_bal_{r} = pww_stk_b }}

	pww_stock_cap_{r} = yes

	set_variable = {{ pww_stock_in_{r} = 0 }}
	set_variable = {{ pww_stock_cost_{r} = 0 }}
	set_variable = {{ pww_stock_out_{r} = 0 }}
	if = {{
		# Fill: a share of the unsold leftover, within capacity and the daily
		# rate. By default (c_fill_cost = 0) it is stored WITHOUT a cost
		# modifier: the leftover is unused output, and a resource cost would
		# shrink the export pool (production x min_export), which the AI
		# buys out almost everywhere, so it would cut exports.
		limit = {{
			check_variable = {{ pww_stk_b > global.pww_stock_c_min_flow }}
			check_variable = {{ pww_stock_{r} < pww_stock_cap_{r} }}
		}}
		set_temp_variable = {{ pww_stk_f = pww_stk_b }}
		multiply_temp_variable = {{ pww_stk_f = global.pww_stock_c_fill_share }}
		set_temp_variable = {{ pww_stk_m = pww_stock_cap_{r} }}
		subtract_from_temp_variable = {{ pww_stk_m = pww_stock_{r} }}
		divide_temp_variable = {{ pww_stk_m = global.pww_stock_c_period }}
{tmin("pww_stk_f", "pww_stk_m")}		set_temp_variable = {{ pww_stk_m = pww_stock_cap_{r} }}
		multiply_temp_variable = {{ pww_stk_m = global.pww_stock_c_fill_rate }}
{tmin("pww_stk_f", "pww_stk_m")}		set_temp_variable = {{ pww_stk_cst = pww_stk_f }}
		multiply_temp_variable = {{ pww_stk_cst = global.pww_stock_c_fill_cost }}
		# A cartel quota (pww_cartel_store_<res>, units a day) may ask storage
		# to take more: the extra is withheld through the cost modifier
		# (cutting exports is the quota's purpose), within B and capacity.
		if = {{
			limit = {{ check_variable = {{ pww_cartel_store_{r} > pww_stk_f }} }}
			set_temp_variable = {{ pww_stk_g = pww_cartel_store_{r} }}
			if = {{ limit = {{ check_variable = {{ pww_stk_g > pww_stk_b }} }} set_temp_variable = {{ pww_stk_g = pww_stk_b }} }}
			set_temp_variable = {{ pww_stk_m = pww_stock_cap_{r} }}
			subtract_from_temp_variable = {{ pww_stk_m = pww_stock_{r} }}
			divide_temp_variable = {{ pww_stk_m = global.pww_stock_c_period }}
			if = {{ limit = {{ check_variable = {{ pww_stk_g > pww_stk_m }} }} set_temp_variable = {{ pww_stk_g = pww_stk_m }} }}
			if = {{
				limit = {{ check_variable = {{ pww_stk_g > pww_stk_f }} }}
				add_to_temp_variable = {{ pww_stk_cst = pww_stk_g }}
				subtract_from_temp_variable = {{ pww_stk_cst = pww_stk_f }}
				set_temp_variable = {{ pww_stk_f = pww_stk_g }}
			}}
		}}
		if = {{
			limit = {{ check_variable = {{ pww_stk_f > global.pww_stock_c_min_flow }} }}
			set_variable = {{ pww_stock_in_{r} = pww_stk_f }}
			set_variable = {{ pww_stock_cost_{r} = pww_stk_cst }}
		}}
	}}
	else_if = {{
		# Draw: cover the shortfall, capped by throughput (a share of
		# capacity a day) and by what lasts until the next tick.
		limit = {{
			check_variable = {{ pww_stk_b < global.pww_stock_c_min_flow_neg }}
			check_variable = {{ pww_stock_{r} > global.pww_stock_c_min_flow }}
		}}
		set_temp_variable = {{ pww_stk_f = pww_stk_b }}
		multiply_temp_variable = {{ pww_stk_f = -1 }}
		set_temp_variable = {{ pww_stk_m = pww_stock_cap_{r} }}
		multiply_temp_variable = {{ pww_stk_m = global.pww_stock_c_draw_rate }}
{tmin("pww_stk_f", "pww_stk_m")}		set_temp_variable = {{ pww_stk_m = pww_stock_{r} }}
		divide_temp_variable = {{ pww_stk_m = global.pww_stock_c_period }}
{tmin("pww_stk_f", "pww_stk_m")}		if = {{
			limit = {{ check_variable = {{ pww_stk_f > global.pww_stock_c_min_flow }} }}
			set_variable = {{ pww_stock_out_{r} = pww_stk_f }}
		}}
	}}
}}

pww_stock_cap_{r} = {{
	# Demand = met use + shortfall (resource_consumed is met use only: it
	# reads 0 for a country that has none of the resource).
	set_temp_variable = {{ pww_stk_use = resource_consumed@{r} }}
	if = {{
		limit = {{ check_variable = {{ resource@{r} < 0 }} }}
		subtract_from_temp_variable = {{ pww_stk_use = resource@{r} }}
	}}
	set_temp_variable = {{ pww_stk_sc = pww_stk_use }}
	if = {{ limit = {{ check_variable = {{ pww_stk_sc < global.pww_stock_c_min_scale }} }} set_temp_variable = {{ pww_stk_sc = global.pww_stock_c_min_scale }} }}
	multiply_temp_variable = {{ pww_stk_sc = global.pww_stock_c_base_days }}
	set_temp_variable = {{ pww_stk_lv = pww_stock_depots }}
	multiply_temp_variable = {{ pww_stk_lv = global.pww_stock_c_depot_mult }}
	add_to_temp_variable = {{ pww_stk_lv = 1 }}
	multiply_temp_variable = {{ pww_stk_sc = pww_stk_lv }}
	set_variable = {{ pww_stock_cap_{r} = pww_stk_sc }}
	set_temp_variable = {{ pww_stk_fl = pww_stock_{r} }}
	multiply_temp_variable = {{ pww_stk_fl = 100 }}
	divide_temp_variable = {{ var = pww_stk_fl value = pww_stock_cap_{r} if_zero = 0 }}
	clamp_temp_variable = {{ var = pww_stk_fl min = 0 max = 100 }}
	set_variable = {{ pww_stock_fill_{r} = pww_stk_fl }}
	if = {{ limit = {{ check_variable = {{ pww_stk_use < 1 }} }} set_temp_variable = {{ pww_stk_use = 1 }} }}
	set_temp_variable = {{ pww_stk_dy = pww_stock_{r} }}
	divide_temp_variable = {{ pww_stk_dy = pww_stk_use }}
	clamp_temp_variable = {{ var = pww_stk_dy min = 0 max = 9999 }}
	set_variable = {{ pww_stock_days_{r} = pww_stk_dy }}
}}

pww_stock_value_{r} = {{
	pww_stock_tension_factor = yes
	set_temp_variable = {{ pww_stv_g = pww_stock_fill_{r} }}
	divide_temp_variable = {{ pww_stv_g = 100 }}
	multiply_temp_variable = {{ pww_stv_g = pww_stv_g }}
	multiply_temp_variable = {{ pww_stv_g = -1 }}
	add_to_temp_variable = {{ pww_stv_g = 1 }}
	clamp_temp_variable = {{ var = pww_stv_g min = 0 max = 1 }}
	set_temp_variable = {{ pww_stock_unit_value = global.pww_stock_c_market }}
	multiply_temp_variable = {{ pww_stock_unit_value = pww_stv_t }}
	multiply_temp_variable = {{ pww_stock_unit_value = pww_stv_g }}
}}

pww_stock_seize_{r} = {{
	set_temp_variable = {{ pww_stk_s = pww_stock_{r} }}
	multiply_temp_variable = {{ pww_stk_s = global.pww_stock_c_seize }}
	subtract_from_variable = {{ pww_stock_{r} = pww_stk_s }}
	pww_stock_cap_{r} = yes
	FROM = {{
		add_to_variable = {{ pww_stock_{r} = pww_stk_s }}
		pww_stock_cap_{r} = yes
		if = {{
			limit = {{ check_variable = {{ pww_stock_{r} > pww_stock_cap_{r} }} }}
			set_variable = {{ pww_stock_{r} = pww_stock_cap_{r} }}
			pww_stock_cap_{r} = yes
		}}
	}}
}}

""")
    # Loops over all six for the core file.
    out.append("# All six resources (called by pww_stock_core.txt).\n")
    for name, body in (("pww_stock_tick_all", "pww_stock_tick_{r} = yes"),
                       ("pww_stock_cap_all", "pww_stock_cap_{r} = yes"),
                       ("pww_stock_seize_all", "pww_stock_seize_{r} = yes")):
        out.append(f"{name} = {{\n" + "".join(f"\t{body.format(r=r)}\n" for r in RES) + "}\n\n")
    out.append("""# Country scope. Temp out pww_stk_prod (sum produced), pww_stk_cons (sum
# consumed), pww_stk_imp (sum imported) over the six stored resources.
pww_stock_sum_readings = {
""" + "".join(
        f"\tadd_to_temp_variable = {{ pww_stk_prod = resource_produced@{r} }}\n"
        f"\tadd_to_temp_variable = {{ pww_stk_cons = resource_consumed@{r} }}\n"
        f"\tadd_to_temp_variable = {{ pww_stk_imp = resource_imported@{r} }}\n" for r in RES)
        + "}\n\n")
    return "".join(out)


def triggers() -> str:
    out = [HEADER, """###############################################################################
# Power Without War: stockpiles triggers (country scope)
#   pww_stock_full_<res>   the reserve is at least global.pww_stock_c_full % full
#   pww_stock_has_<res>    the reserve holds at least 1 unit-day
###############################################################################

"""]
    for r in RES:
        out.append(f"""pww_stock_full_{r} = {{
	check_variable = {{ pww_stock_fill_{r} > global.pww_stock_c_full }}
}}

pww_stock_has_{r} = {{
	check_variable = {{ pww_stock_{r} > 0.999 }}
}}

""")
    return "".join(out)


def modifiers() -> str:
    lines = [HEADER, """###############################################################################
# Power Without War: stockpiles dynamic modifier (one per active country).
#   pww_stock_cost_<res> units a day withheld from output into the reserve
#                        (cartel quota requests; all intake if c_fill_cost = 1)
#   pww_stock_out_<res>  units a day drawn from the reserve to cover a deficit
# Stacks with the ledger's pww_ledger_flows. Depot construction locks its
# civilian factories through the decision's own modifier, not here.
###############################################################################

pww_stock_flows = {
	enable = { always = yes }
	icon = GFX_idea_export_focus

"""]
    for r in RES:
        lines.append(f"\tcountry_resource_cost_{r} = pww_stock_cost_{r}\n")
    lines.append("\n")
    for r in RES:
        lines.append(f"\tcountry_resource_{r} = pww_stock_out_{r}\n")
    lines.append("}\n")
    return "".join(lines)


def loc() -> str:
    rows = "\\n".join(
        f"{NAMES[r]}: [?ROOT.pww_stock_{r}|0] in store (~[?ROOT.pww_stock_days_{r}|0] days of use), [?ROOT.pww_stock_fill_{r}|0]% full" for r in RES)
    entries = [
        ("pww_stock_flows", "Strategic Reserves"),
        ("pww_stock_flows_desc", "Spare resources moving into storage, and stored resources covering shortages."),
        ("pww_stock_category", "Strategic Reserves"),
        ("pww_stock_category_desc",
         "Resources we cannot sell go into storage on their own, and storage covers shortages on its own. "
         "Stored stock slowly shrinks (about 2% a month). Depots let us store more.\\n\\n"
         f"Depots built: [?ROOT.pww_stock_depots|0] of [?global.pww_stock_c_depot_max|0]\\n{rows}"),
        ("pww_stock_build_depot", "Build Strategic Depots"),
        ("pww_stock_build_depot_desc",
         "Put civilian factories to work on warehouses and rail sidings. When the depots are finished, "
         "every resource reserve can hold more and release it faster in a shortage."),
        ("pww_stock_depot_done_tt", "When finished: every resource reserve can hold §Gmore§! and release it faster."),
        ("pww_stock_depot_max_tt", "Fewer than [?global.pww_stock_c_depot_max|0] depots built"),
    ]
    return "﻿l_english:\n" + "".join(f' {k}: "{v}"\n' for k, v in entries)


def write(path: Path, text: str, bom: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    path.write_bytes(data)
    print(f"wrote {path.relative_to(REPO)}")


def main() -> None:
    write(MOD / "common/scripted_effects/pww_stock_res.txt", effects())
    write(MOD / "common/scripted_triggers/pww_stock_triggers.txt", triggers())
    write(MOD / "common/dynamic_modifiers/pww_stock_dynamic_modifiers.txt", modifiers())
    write(MOD / "localisation/english/pww_stock_l_english.yml", loc())


if __name__ == "__main__":
    main()
